export function getAllPhotos(): Photo[] {
  return [...photos];
}

export function getFeaturedPhotos(): Photo[] {
  return photos.filter((p) => p.featured);
}

export function getHeroPhoto(): Photo | undefined {
  return photos.find((p) => p.hero);
}

export function getPhotoBySlug(slug: string): Photo | undefined {
  return photos.find((p) => p.slug === slug);
}

export function getPhotosByTag(tag: string): Photo[] {
  return getAllPhotos().filter((p) => p.tags.includes(tag));
}

export function getAllTags(): string[] {
  const tagSet = new Set<string>();
  photos.forEach((p) => p.tags.forEach((t) => tagSet.add(t)));
  return Array.from(tagSet).sort();
}

export function getAdjacentPhotos(slug: string): {
  prev: Photo | null;
  next: Photo | null;
} {
  const all = getAllPhotos();
  const index = all.findIndex((p) => p.slug === slug);
  return {
    prev: index > 0 ? all[index - 1] : null,
    next: index < all.length - 1 ? all[index + 1] : null,
  };
}
